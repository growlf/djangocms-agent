#!/usr/bin/env bash
# Create .env for the Docker stack with a random DB password and Django secret key.
# Never overwrites an existing .env and never prints the secrets.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -e .env ]; then
    echo ".env already exists; leaving it untouched."
    exit 0
fi

# Random URL-safe secret of about $1 bytes of entropy. python3 first, openssl as a fallback.
rand() {
    if command -v python3 >/dev/null 2>&1; then
        python3 -c "import secrets, sys; print(secrets.token_urlsafe(int(sys.argv[1])))" "$1"
    elif command -v openssl >/dev/null 2>&1; then
        openssl rand -base64 "$(( $1 * 2 ))" | tr -d '\n=' | tr '+/' '-_' | cut -c1-"$(( $1 * 4 / 3 ))"
    else
        return 1
    fi
}

# Generate BOTH secrets before anything is written: a failure must never leave an .env with empty
# values (it would then be "already present" forever and the stack could not start).
sk=$(rand 50) || { echo "Cannot generate secrets: install python3 or openssl. No .env was written." >&2; exit 1; }
pw=$(rand 32) || { echo "Cannot generate secrets: install python3 or openssl. No .env was written." >&2; exit 1; }
if [ -z "$sk" ] || [ -z "$pw" ]; then
    echo "Secret generation returned an empty value. No .env was written." >&2
    exit 1
fi

umask 077
tmp=$(mktemp .env.XXXXXX)
trap 'rm -f "$tmp"' EXIT
{
    echo "# Generated by bin/docker-env.sh. Gitignored; do not commit."
    echo "DJANGO_SECRET_KEY=$sk"
    echo "DB_NAME=__PROJECT_NAME__"
    echo "DB_USER=__PROJECT_NAME__"
    echo "DB_PASSWORD=$pw"
} > "$tmp"
chmod 600 "$tmp"
mv "$tmp" .env
trap - EXIT
echo "Created .env (mode 600) with generated secrets."
